"""Кастомные исключения приложения daily."""

# HTTP-коды, при которых повторная попытка имеет смысл: сервис временно
# недоступен или перегружен. Все прочие коды считаем терминальными,
# чтобы не делать бессмысленные ретраи (например, на 400 Bad Request).
RETRYABLE_STATUS_CODES = frozenset({408, 425, 429, 500, 502, 503, 504})


class NotificationError(Exception):
    """Базовое исключение для ошибок отправки уведомлений (Telegram, HTTP и др.)."""

    def __init__(self, message="Ошибка при отправке уведомления", details=None):
        super().__init__(message)
        # Здесь можно хранить код ответа API или сырой ответ сервера
        self.details = details or {}
